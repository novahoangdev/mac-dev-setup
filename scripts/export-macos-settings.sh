#!/usr/bin/env bash
# ==============================================================================
# scripts/export-macos-settings.sh
# Reads the current macOS preferences (keyboard, trackpad, Finder, Dock…) and
# writes backups/apply-my-settings.sh, which restores them on another Mac.
# Usage: bash scripts/export-macos-settings.sh [--vi|--en]   (English by default)
# Read-only on this Mac: it only runs `defaults read`.
# ==============================================================================

set -euo pipefail

UI_LANG=en
case "${1:-}" in --vi) UI_LANG=vi ;; --en) UI_LANG=en ;; esac
t() { if [ "$UI_LANG" = vi ]; then printf '%s' "$2"; else printf '%s' "$1"; fi; }

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUTPUT_FILE="$PROJECT_ROOT/backups/apply-my-settings.sh"
mkdir -p "$(dirname "$OUTPUT_FILE")"

echo "🔍 $(t "Reading current macOS preferences..." "Đang đọc cài đặt macOS hiện tại...")"

cat > "$OUTPUT_FILE" <<EOF
#!/usr/bin/env bash
# ==============================================================================
# apply-my-settings.sh — restores personal macOS preferences.
# Generated by scripts/export-macos-settings.sh on $(date +%Y-%m-%d).
# Run: bash backups/apply-my-settings.sh
# ==============================================================================

echo "🚀 $(t "Applying macOS preferences..." "Đang áp dụng cài đặt macOS...")"

# Quit System Settings so it does not overwrite the new values
osascript -e 'tell application "System Settings" to quit' 2>/dev/null || true

EOF

# export_keys <domain> <title> <key>...
export_keys() {
  local domain="$1" title="$2" key val type lines=""
  shift 2
  for key in "$@"; do
    val=$(defaults read "$domain" "$key" 2>/dev/null) || continue
    type=$(defaults read-type "$domain" "$key" 2>/dev/null | awk '{print $NF}' || true)
    case "$type" in
      boolean) [ "$val" = 1 ] && val=true || val=false
               lines+="defaults write $domain \"$key\" -bool $val"$'\n' ;;
      integer) lines+="defaults write $domain \"$key\" -int $val"$'\n' ;;
      float)   lines+="defaults write $domain \"$key\" -float $val"$'\n' ;;
      string)  lines+="defaults write $domain \"$key\" -string \"${val//\"/\\\"}\""$'\n' ;;
      *)       ;; # arrays/dicts are skipped on purpose
    esac
  done
  [ -z "$lines" ] && return 0
  printf 'echo "⚙️  %s"\n%s\n' "$title" "$lines" >> "$OUTPUT_FILE"
}

export_keys -g "$(t "Keyboard & text input" "Bàn phím & nhập liệu")" \
  InitialKeyRepeat KeyRepeat ApplePressAndHoldEnabled \
  NSAutomaticSpellingCorrectionEnabled NSAutomaticCapitalizationEnabled \
  NSAutomaticPeriodSubstitutionEnabled NSAutomaticQuoteSubstitutionEnabled \
  NSAutomaticDashSubstitutionEnabled

TRACKPAD_KEYS=(Clicking TrackpadThreeFingerDrag TrackpadRightClick TrackpadCornerSecondaryClick
  TrackpadScroll TrackpadPinch TrackpadRotate TrackpadTwoFingerDoubleTapGesture
  TrackpadThreeFingerTapGesture TrackpadThreeFingerHorizSwipeGesture TrackpadThreeFingerVertSwipeGesture
  TrackpadFourFingerHorizSwipeGesture TrackpadFourFingerVertSwipeGesture
  TrackpadFourFingerPinchGesture TrackpadFiveFingerPinchGesture)
export_keys com.apple.AppleMultitouchTrackpad "$(t "Trackpad gestures" "Cử chỉ trackpad")" "${TRACKPAD_KEYS[@]}"
export_keys com.apple.driver.AppleBluetoothMultitouch.trackpad "$(t "Bluetooth trackpad gestures" "Cử chỉ trackpad Bluetooth")" "${TRACKPAD_KEYS[@]}"

export_keys -g "$(t "Pointer & scroll speed" "Tốc độ con trỏ & cuộn")" \
  com.apple.trackpad.scaling com.apple.mouse.scaling com.apple.scrollwheel.scaling \
  com.apple.swipescrolldirection

export_keys com.apple.finder "Finder" \
  ShowPathbar ShowStatusBar _FXSortFoldersFirst FXDefaultSearchScope \
  FXEnableExtensionChangeWarning FXPreferredViewStyle AppleShowAllFiles
export_keys NSGlobalDomain "$(t "File extensions" "Đuôi file")" AppleShowAllExtensions
export_keys com.apple.desktopservices "$(t "No .DS_Store on network/USB drives" "Không tạo .DS_Store trên ổ mạng/USB")" \
  DSDontWriteNetworkStores DSDontWriteUSBStores

export_keys com.apple.dock "Dock & Mission Control" \
  autohide autohide-delay autohide-time-modifier tilesize magnification largesize \
  orientation show-recents mru-spaces

export_keys com.apple.screencapture "$(t "Screenshots" "Chụp màn hình")" location type disable-shadow

cat >> "$OUTPUT_FILE" <<EOF
echo "🔄 $(t "Restarting Finder, Dock and SystemUIServer..." "Khởi động lại Finder, Dock và SystemUIServer...")"
killall Finder Dock SystemUIServer 2>/dev/null || true

echo "✅ $(t "Done. Some trackpad settings need a logout to take effect." "Xong. Một số cài đặt trackpad cần đăng xuất để có hiệu lực.")"
EOF

chmod +x "$OUTPUT_FILE"

echo "✅ $(t "Exported to" "Đã xuất ra") backups/apply-my-settings.sh"
echo "👉 $(t "On the new Mac run:" "Trên máy Mac mới chạy:") bash backups/apply-my-settings.sh"
